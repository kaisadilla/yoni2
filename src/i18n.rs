use crate::cmd::util::CmdContext;
use crate::util::{Data, Error};
use include_dir::Dir;
use poise::Command;
use rand::seq::IteratorRandom;
use std::borrow::Cow;
use std::collections::{HashMap, HashSet};
use std::fmt::Display;
use std::sync::Arc;
use tracing::{error, info};

pub static LANG_DIR: Dir =
  include_dir::include_dir!("$CARGO_MANIFEST_DIR/lang");

pub struct I18n {
  default_lang: String,
  languages: HashMap<String, toml::Table>,
}

impl I18n {
  pub fn load(default_lang: impl Into<String>) -> Self {
    let mut languages = HashMap::new();

    for file in LANG_DIR.files() {
      let path = file.path().display();

      if file.path().extension().and_then(|ext| ext.to_str()) != Some("toml") {
        continue;
      }

      let locale =
        file.path().file_stem().unwrap().to_str().unwrap().to_owned();

      let table = toml::from_str(file.contents_utf8().unwrap())
        .unwrap_or_else(|err| panic!("Invalid language file {path}: {err}"));

      languages.insert(locale, table);
    }

    Self { default_lang: default_lang.into(), languages }
  }

  /// Returns a locale with the language that should be used for the specific
  /// context given. That is: the server's language if possible, else the bot's
  /// default language.
  pub async fn locale(self: &Arc<Self>, ctx: &CmdContext<'_>) -> Locale {
    Locale {
      i18n: self.clone(),
      lang: match ctx {
        CmdContext::Application(actx) => actx.interaction.guild_locale.clone(),
        CmdContext::Prefix(_) => {
          ctx.partial_guild().await.map(|g| g.preferred_locale)
        },
      }
      .unwrap_or_else(|| self.default_lang.clone()),
    }
  }

  /// Returns a locale with the bot's default language.
  pub fn default_locale(self: &Arc<Self>) -> Locale {
    Locale { i18n: self.clone(), lang: self.default_lang.clone() }
  }

  /// Localizes the commands given. This will also change their default names,
  /// descriptions, etc. to the ones provided by the default language; so these
  /// names (rather than the ones generated by Poise) will be used in any
  /// language that doesn't have its own localization.
  pub fn localize_commands(
    self: &Arc<Self>,
    commands: &mut Vec<Command<Data, Error>>,
  ) {
    let locale = self.default_locale();
    for cmd in commands {
      self.localize_command(cmd, &String::from("commands"), &locale);
    }
  }

  /// Localizes the command given.
  ///
  /// ## Parameters
  /// * `path`: The path that contains the keys for this command in the
  /// localization file.
  /// * `default`: A [`Locale`] to use as the default language - the command's
  /// native name, desc, etc. will be overriden by this locale, if it contains
  /// the necessary keys.
  pub fn localize_command(
    self: &Arc<Self>,
    command: &mut Command<Data, Error>,
    path: &String,
    default: &Locale,
  ) {
    // The path used by subcommands of this command. We build it first so it's
    // not affected by us changing the command's name.
    let subcmd_path = format!("{path}.{}", command.name);

    // If a command's name is "name", it uses the "_name" key instead to avoid
    // key collisions. Same goes for parameters and choices.
    let cmd_key =
      if command.name == "name" { "_name" } else { &command.name.clone() };

    info!(command = %command.name, key = %cmd_key, %path, "Localizing command.");

    let name_key = format!("{path}.{cmd_key}.name");
    let desc_key = format!("{path}.{cmd_key}.desc");

    command.name_localizations = self.localizations(&name_key);
    command.description_localizations = self.localizations(&desc_key);

    if let Some(name) = default.get(&name_key) {
      command.name = Cow::Owned(name.into());
    }
    if let Some(desc) = default.get(&desc_key) {
      command.description = Some(Cow::Owned(desc.into()));
    }

    for param in &mut command.parameters {
      let param_key = if param.name == "name" { "_name" } else { &param.name };
      let param_path = format!("{path}.{cmd_key}.{param_key}");

      let param_name_key = param_path.clone() + ".name";
      let param_desc_key = param_path.clone() + ".desc";

      param.name_localizations = self.localizations(&param_name_key);
      param.description_localizations = self.localizations(&param_desc_key);

      if let Some(name) = default.get(&param_name_key) {
        param.name = Cow::Owned(name.into());
      }
      if let Some(desc) = default.get(&param_desc_key) {
        param.description = Some(Cow::Owned(desc.into()));
      }

      for choice in param.choices.to_mut() {
        let choice_key =
          if choice.name == "name" { "_name" } else { &choice.name };

        let choice_key = format!("{param_path}.{choice_key}.name");

        choice.localizations = self.localizations(&choice_key);

        if let Some(name) = default.get(&choice_key) {
          choice.name = Cow::Owned(name.into());
        }
      }
    }

    for subcommand in &mut command.subcommands {
      self.localize_command(subcommand, &subcmd_path, default);
    }
  }

  /// Retrieves the string for the key and locale given if it exists. If the
  /// value associated to the given key is an array of strings, returns one of
  /// these at random.
  pub fn get(&self, locale: &str, key: &str) -> Option<&str> {
    let mut current_key = key.to_owned();
    let mut visited = HashSet::new();

    // A loop to resolve redirects (values in the format of `::key`).
    loop {
      if visited.insert(current_key.clone()) == false {
        error!(origin = key, "Lang keys form a circular dependency.");
      }

      let mut path = current_key.split('.');
      let mut val = self.languages.get(locale)?.get(path.next()?)?;

      for name in path {
        val = val.as_table()?.get(name)?;
      }

      let val = match val {
        toml::Value::String(val) => val.as_str(),

        toml::Value::Array(vals) => {
          // If the value array doesn't contain any string, we return None.
          if vals.iter().any(|v| matches!(v, toml::Value::String(_)) == false) {
            return None;
          }

          // Return a string inside the array at random. If the array is empty,
          // returns None.
          match vals
            .iter()
            .filter_map(toml::Value::as_str)
            .choose(&mut rand::rng())
          {
            Some(v) => v,
            None => return None,
          }
        },

        _ => return None,
      };

      if let Some(alias) = val.strip_prefix("::") {
        current_key = alias.to_owned();
      } else {
        return Some(val);
      }
    }
  }

  pub fn default_lang(&self) -> &str {
    self.default_lang.as_str()
  }

  /// Retrieves the definite string for the key and locale given.
  pub fn t<'a>(&'a self, locale: &'a str, key: &'a str) -> &'a str {
    self
      .get(locale, key)
      .or_else(|| self.get(&self.default_lang, key))
      .unwrap_or(key)
  }

  /// Retrieves the definite string for the key and locale given, applying
  /// the arguments given to the string's template parameters.
  pub fn f(
    &self,
    locale: &str,
    key: &str,
    args: &[(&str, &(dyn Display + Send + Sync))],
  ) -> String {
    let Some(base) =
      self.get(locale, key).or_else(|| self.get(&self.default_lang, key))
    else {
      return String::from(key);
    };

    let mut res = base.to_string();

    for (k, v) in args {
      res = res.replace(&format!("{{{}}}", k), &format!("{v}"));
    }

    res
  }

  /// Retrieves the definite string for a boolean value (true or false).
  pub fn b(&self, locale: &str, val: bool) -> &str {
    let key = if val { "value.bool.true" } else { "value.bool.false" };

    self
      .get(locale, key)
      .or_else(|| self.get(&self.default_lang, key))
      .unwrap_or(key)
  }

  pub fn locales(&self) -> impl Iterator<Item = &str> {
    self.languages.keys().map(String::as_str)
  }

  /// Collects every locale's translation of the key given into a Discord-ready
  /// localization map (langcode -> string). Locales that don't define the key
  /// are simply omitted, so Discord falls back to the command's base name and
  /// description for them.
  pub fn localizations(
    &self,
    key: &str,
  ) -> Cow<'static, [(Cow<'static, str>, Cow<'static, str>)]> {
    Cow::Owned(
      self
        .languages
        .keys()
        .filter_map(|locale| {
          self
            .get(locale, key)
            .map(|val| (Cow::Owned(locale.clone()), Cow::Owned(val.to_owned())))
        })
        .collect(),
    )
  }
}

/// Wraps an I18n instance and returns values from it with the language assigned
/// to this Locale.
pub struct Locale {
  lang: String,
  i18n: Arc<I18n>,
}

impl Locale {
  pub fn get<'a>(&'a self, key: &'a str) -> Option<&'a str> {
    self.i18n.get(&self.lang, key)
  }

  /// Retrieves the definite string for the key and locale given.
  pub fn t<'a>(&'a self, key: &'a str) -> &'a str {
    self.i18n.t(&self.lang, key)
  }

  /// Retrieves the definite string for the key and locale given, applying
  /// the arguments given to the string's template parameters.
  pub fn fmt(
    &self,
    key: &str,
    args: &[(&str, &(dyn Display + Send + Sync))],
  ) -> String {
    self.i18n.f(&self.lang, key, args)
  }

  /// Retrieves the definite string for a boolean value (true or false).
  pub fn bool(&self, val: bool) -> &str {
    self.i18n.b(&self.lang, val)
  }
}
