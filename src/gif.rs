use crate::download::download;
use crate::util::Hash;
use anyhow::{Context, ensure};
use image::codecs::gif::GifDecoder;
use image::{AnimationDecoder, ImageDecoder, Rgb, RgbImage, RgbaImage};
use image_hasher::{HashAlg, Hasher, HasherConfig};
use sha2::{Digest, Sha256};
use std::io::Cursor;
use tracing::debug;

pub const MAX_GIF_SIZE: usize = 12 * 1024 * 1024; // 12 MiB

const SAMPLE_COUNT: usize = 16;
const MAX_FRAMES: usize = 300;
const MAX_DIMENSION: u32 = 2048;
const MAX_DECODER_MEMORY: u64 = 32 * 1024 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq, sqlx::Type)]
#[sqlx(rename_all = "lowercase")]
pub enum GifStatus {
  Allowed,
  Disabled,
  Banned,
}

pub struct Gif {
  bytes: Vec<u8>,
}

impl Gif {
  pub fn new(bytes: Vec<u8>) -> Self {
    Self { bytes }
  }

  pub async fn download(
    client: &reqwest::Client,
    url: &str,
  ) -> anyhow::Result<Self> {
    debug!(gif_url = %url, "Downloading GIF");
    let bytes = download(client, url, MAX_GIF_SIZE).await?;

    anyhow::ensure!(bytes.starts_with(b"GIF8"), "Downloaded file isn't a GIF.");

    Ok(Self { bytes })
  }

  /// Generates a simple hash code that is unique for the exact file given. This
  /// hash code is not stable across re-encodings.
  pub fn exact_hash(&self) -> Hash {
    Sha256::digest(&self.bytes).into()
  }

  /// Generates a hash code from the images generated by this GIF. This hash code
  /// resists GIF re-encodings and redundant frames, for as long as the rendered
  /// result of the GIF is the same.
  pub fn visual_hash(&self) -> anyhow::Result<Hash> {
    let decoder = GifDecoder::new(Cursor::new(&self.bytes))?;

    let mut seq_hash = Sha256::new();
    seq_hash.update(b"gif-pixel-sequence-v1");

    let mut prev_frame: Option<Hash> = None;
    let mut frame_count = 0u32;

    for frame in decoder.into_frames() {
      let img = frame?.into_buffer();

      let mut frame_hash = Sha256::new();

      frame_hash.update(img.width().to_le_bytes());
      frame_hash.update(img.height().to_le_bytes());
      frame_hash.update(img.as_raw());

      let frame_hash: Hash = frame_hash.finalize().into();

      // Ignore consecutive identical frames. This makes the result independent
      // of redundant frames introduced by GIF reencoding.
      if prev_frame != Some(frame_hash) {
        seq_hash.update(frame_hash);
        prev_frame = Some(frame_hash);
        frame_count += 1;
      }
    }

    anyhow::ensure!(frame_count > 0, "GIF contains now frames");

    seq_hash.update(frame_count.to_le_bytes());

    Ok(seq_hash.finalize().into())
  }

  /// Generates a hash code for this GIF. Similar GIFs produce similar hashes,
  /// which can be used to detect GIFs that may be slight edits of other GIFs.
  pub fn similarity_hash(&self) -> anyhow::Result<GifPHash> {
    let mut decoder =
      GifDecoder::new(Cursor::new(&self.bytes)).context("Invalid GIF")?;

    let mut limits = image::Limits::default();
    limits.max_image_width = Some(MAX_DIMENSION);
    limits.max_image_height = Some(MAX_DIMENSION);
    limits.max_alloc = Some(MAX_DECODER_MEMORY);

    decoder.set_limits(limits)?;

    let hasher = HasherConfig::new()
      .hash_size(8, 8)
      .hash_alg(HashAlg::Median)
      .preproc_dct()
      .to_hasher();

    let mut frames = Vec::new();
    let mut total_duration_ms = 0u64;

    for (idx, frame) in decoder.into_frames().enumerate() {
      ensure!(idx < MAX_FRAMES, "GIF exceeds maximum frame count.");

      let frame = frame?;

      let hash = frame_phash(&hasher, frame.buffer());
      let duration_ms = delay_ms(frame.delay());

      total_duration_ms = total_duration_ms
        .checked_add(duration_ms)
        .context("GIF duration overflow")?;

      frames.push(TimedFrame { hash, duration_ms });
    }

    ensure!(frames.is_empty() == false, "GIF contains no frames.");

    Ok(GifPHash { samples: sample_frames(&frames, total_duration_ms) })
  }
}

/// Returns the pHash for one fully decoded frame.
fn frame_phash(hasher: &Hasher, frame: &RgbaImage) -> u64 {
  let rgb = RgbImage::from_fn(frame.width(), frame.height(), |x, y| {
    let [r, g, b, a] = frame.get_pixel(x, y).0;
    let a = u16::from(a);

    let blend =
      |chan: u8| ((u16::from(chan) * a + 255 * (255 - a) + 127) / 255) as u8;

    Rgb([blend(r), blend(g), blend(b)])
  });

  let hash = hasher.hash_image(&rgb);

  u64::from_le_bytes(
    hash.as_bytes().try_into().expect("Expected an 8-byte pHash"),
  )
}

/// Returns the frame duration in ms.
fn delay_ms(delay: image::Delay) -> u64 {
  let (numer, denom) = delay.numer_denom_ms();

  if denom == 0 {
    return 10;
  }

  ((u64::from(numer) * u64::from(denom) / 2) / u64::from(denom)).max(10)
}

struct TimedFrame {
  hash: u64,
  duration_ms: u64,
}

/// Sample the animation at equally spaced points in normalized time.
fn sample_frames(
  frames: &[TimedFrame],
  total_duration_ms: u64,
) -> [u64; SAMPLE_COUNT] {
  let mut samples = [0u64; SAMPLE_COUNT];

  let mut frame_idx = 0;
  let mut frame_end = frames[0].duration_ms;

  for (i, sample) in samples.iter_mut().enumerate() {
    let target = ((2 * i + 1) as u128 * u128::from(total_duration_ms)
      / (2 * SAMPLE_COUNT) as u128) as u64;

    while frame_idx + 1 < frames.len() && target >= frame_end {
      frame_idx += 1;
      frame_end = frame_end.saturating_add(frames[frame_idx].duration_ms);
    }

    *sample = frames[frame_idx].hash;
  }

  samples
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GifPHash {
  samples: [u64; SAMPLE_COUNT],
}

impl GifPHash {
  // Builds a PHash from the BLOB given.
  pub fn from_blob(blob: &[u8]) -> Option<Self> {
    if blob.len() != SAMPLE_COUNT * 8 {
      return None;
    }

    let samples = std::array::from_fn(|i| {
      let start = i * 8;

      u64::from_le_bytes(blob[start..start + 8].try_into().unwrap())
    });

    Some(Self { samples })
  }

  /// Returns the average Hamming distance between two animation fingerprints.
  ///
  /// Range: 0..=64. Lower means more similar.
  pub fn mean_hamming_distance(&self, other: &Self) -> f32 {
    let total: u32 = self
      .samples
      .iter()
      .zip(other.samples.iter())
      .map(|(a, b)| (a ^ b).count_ones())
      .sum();

    total as f32 / SAMPLE_COUNT as f32
  }

  /// Returns whether two GIFs are perceptually similar.
  pub fn is_similar(&self, other: &Self, max_distance: f32) -> bool {
    self.mean_hamming_distance(other) <= max_distance
  }

  /// Serializes the fingerprint into a 128-byte SQLite BLOB.
  pub fn to_blob(&self) -> Vec<u8> {
    let mut blob = Vec::with_capacity(SAMPLE_COUNT * 8);

    for sample in self.samples {
      blob.extend_from_slice(&sample.to_le_bytes());
    }

    blob
  }
}
